const parsed = {};
for (const [ch, strokes] of Object.entries(GLYPHS)) {
  parsed[ch] = strokes.map((st) => st.split(' ').map((p) => p.split(',').map(Number)));
}

export function textWidth(text, size) {
  return text.length * size * (6 / 6) - size * (2 / 6);
}

// Line data for `text` with its top-left at (x, y); `size` is the cap height.
export function textLines(text, x, y, size, style) {
  const out = [];
  const s = size / 6;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = parsed[ch];
    if (g) {
      for (const stroke of g) {
        for (let i = 1; i < stroke.length; i++) {
          out.push({
            type: 2, style,
            x1: cx + stroke[i - 1][0] * s, y1: y + stroke[i - 1][1] * s,
            x2: cx + stroke[i][0] * s, y2: y + stroke[i][1] * s,
          });
        }
      }
    }
    cx += 6 * s;
  }
  return out;
}
